            function updateSlideText() {
                var activeItem = owl.find('.owl-item.active .banner-two__image');
                if (activeItem.length === 0) {
                    var carousel = owl.data('owl.carousel');
                    if (carousel) {
                        var currentIndex = carousel.current();
                        var allItems = owl.find('.owl-item');
                        if (allItems.length > currentIndex) {
                            activeItem = $(allItems[currentIndex]).find('.banner-two__image');
                        }
                    }
                }
                if (activeItem.length > 0) {
                    var classes = activeItem.attr('class') || '';
                    var sliderClass = '';
                    if (classes.indexOf('slider1') !== -1) {
                        sliderClass = 'slider1';
                    } else if (classes.indexOf('slider2') !== -1) {
                        sliderClass = 'slider2';
                    } else if (classes.indexOf('slider3') !== -1) {
                        sliderClass = 'slider3';
                    } else if (classes.indexOf('slider4') !== -1) {
                        sliderClass = 'slider4';
                    } else if (classes.indexOf('slider5') !== -1) {
                        sliderClass = 'slider5';
                    } else if (classes.indexOf('slider6') !== -1) {
                        sliderClass = 'slider6';
                    }
                    $(".slide-text").addClass("d-none");
                    if (sliderClass) {
                        $(".slide-text." + sliderClass).removeClass("d-none");
                    } else {
                        $(".slide-text.slider1").removeClass("d-none");
                    }
                }
            }
            var carousel = owl.data('owl.carousel');
            if (!carousel) {
                setTimeout(initSliderText, 100);
                return;
            }
            owl.on('translated.owl.carousel', function(event) {
                updateSlideText();
            });
            owl.on('changed.owl.carousel', function(event) {
                setTimeout(function() {
                    updateSlideText();
                }, 100);
            });
            setTimeout(function() {
                updateSlideText();
            }, 300);
        }
